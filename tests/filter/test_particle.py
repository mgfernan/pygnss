def _first_particles_from_nodes(nodes: pd.DataFrame, n_particles: int) -> np.array:

    coordinates = nodes[[ipin.X_STR, ipin.Y_STR]]

    min_x, min_y = np.min(coordinates, axis=0)
    max_x, max_y = np.max(coordinates, axis=0)
    dx = (max_x - min_x) / 2.0
    dy = (max_y - min_y) / 2.0

    particles = np.random.uniform((min_x - dx, min_y-dy), (max_x+dx, max_y+dy), (n_particles, 2))

    return particles


